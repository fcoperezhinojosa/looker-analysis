"""Building the final .xlsx from the captured workbook/*.py data files.

This runs suntransfers-yoy-funnel's build.py (vendored under
looker_capture/vendor/yoy_workbook/) against the data*.py files export.py
already writes to output/workbook/. build.py resolves its imports (config,
data, data_ly, ...) relative to its own directory, so it and the eight data
files are assembled into one throwaway build directory before running it.
"""

from __future__ import annotations

import logging
import shutil
import subprocess
import sys
import tempfile
from datetime import date, datetime
from pathlib import Path

from .config import Period

log = logging.getLogger(__name__)

_VENDOR_DIR = Path(__file__).parent / "vendor" / "yoy_workbook"
_BUILD_SCRIPT = _VENDOR_DIR / "build.py"

_DATA_FILES = (
    "data.py",
    "data_ly.py",
    "data_start_search.py",
    "data_start_search_ly.py",
    "data_search.py",
    "data_search_ly.py",
    "data_select_item.py",
    "data_select_item_ly.py",
    "data_add_to_cart.py",
    "data_add_to_cart_ly.py",
    "data_begin_checkout.py",
    "data_begin_checkout_ly.py",
    "data_purchase.py",
    "data_purchase_ly.py",
)

_MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]


class WorkbookBuildError(RuntimeError):
    """build.py failed; stdout/stderr is included so the real cause shows."""


def period_label(period: Period) -> str:
    """Short label used in headers, e.g. "1-23Aug26" or "1Aug-3Sep26"."""
    start, end = period.start, period.end
    yy = f"{end.year % 100:02d}"
    if start.month == end.month and start.year == end.year:
        return f"{start.day}-{end.day}{_MONTHS[start.month - 1][:3]}{yy}"
    if start.year == end.year:
        return (
            f"{start.day}{_MONTHS[start.month - 1][:3]}-"
            f"{end.day}{_MONTHS[end.month - 1][:3]}{yy}"
        )
    return f"{start.isoformat()}_{end.isoformat()}"


def period_full(period: Period) -> str:
    """Full label used in prose, e.g. "1-23 August 2026"."""
    start, end = period.start, period.end
    if start.month == end.month and start.year == end.year:
        return f"{start.day}-{end.day} {_MONTHS[start.month - 1]} {start.year}"
    if start.year == end.year:
        return (
            f"{start.day} {_MONTHS[start.month - 1]} - "
            f"{end.day} {_MONTHS[end.month - 1]} {end.year}"
        )
    return f"{start.isoformat()} to {end.isoformat()}"


def _render_config(
    current: Period, prior: Period, refreshed: str, out_filename: str
) -> str:
    cur_label = period_label(current)
    ly_label = period_label(prior)
    return f'''# Generated by looker-yoy-capture. Do not edit by hand — re-run the capture
# to regenerate.

CUR_LABEL, LY_LABEL = {cur_label!r}, {ly_label!r}
CUR_FULL, LY_FULL = {period_full(current)!r}, {period_full(prior)!r}
CUR_REFRESHED = {refreshed!r}
LY_REFRESHED = {refreshed!r}

OUT = {out_filename!r}

EXTRA_NOTES = []
'''


def build_xlsx(
    workbook_dir: Path,
    current: Period,
    prior: Period,
    out_dir: Path,
    captured_at: str | None = None,
) -> Path:
    """Assemble a build directory and run build.py. Returns the .xlsx path.

    workbook_dir must already contain the eight data*.py files (export.py's
    write_workbook_files output). Raises WorkbookBuildError, with build.py's
    real stdout/stderr, rather than silently producing nothing.
    """
    if not _BUILD_SCRIPT.exists():
        raise WorkbookBuildError(
            f"Vendored build.py missing at {_BUILD_SCRIPT}. Reinstall looker-yoy-capture."
        )

    missing = [f for f in _DATA_FILES if not (workbook_dir / f).exists()]
    if missing:
        raise WorkbookBuildError(
            f"Missing data files in {workbook_dir}: {', '.join(missing)}. "
            "Run a capture with --emit-data-files first."
        )

    refreshed = _format_refreshed(captured_at)
    out_filename = f"Suntransfers_Funnel_YoY_{period_label(current)}_vs_{period_label(prior)}.xlsx"

    with tempfile.TemporaryDirectory(prefix="looker_yoy_build_") as tmp:
        build_dir = Path(tmp)
        shutil.copy2(_BUILD_SCRIPT, build_dir / "build.py")
        for name in _DATA_FILES:
            shutil.copy2(workbook_dir / name, build_dir / name)
        (build_dir / "config.py").write_text(
            _render_config(current, prior, refreshed, out_filename), encoding="utf-8"
        )

        log.info("Running build.py in %s", build_dir)
        result = subprocess.run(
            [sys.executable, "build.py"],
            cwd=build_dir,
            capture_output=True,
            text=True,
            timeout=300,
        )
        if result.returncode != 0:
            raise WorkbookBuildError(
                f"build.py failed (exit {result.returncode}).\n"
                f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
            )
        log.debug("build.py output:\n%s", result.stdout)

        produced = build_dir / out_filename
        if not produced.exists():
            raise WorkbookBuildError(
                f"build.py exited cleanly but {out_filename} was not produced.\n"
                f"--- stdout ---\n{result.stdout}"
            )

        out_dir.mkdir(parents=True, exist_ok=True)
        final_path = out_dir / out_filename
        shutil.copy2(produced, final_path)

    log.info("Wrote %s", final_path)
    return final_path


def _format_refreshed(captured_at: str | None) -> str:
    if not captured_at:
        return datetime.now().strftime("%d/%m/%Y %H:%M")
    try:
        parsed = datetime.strptime(captured_at, "%Y-%m-%d %H:%M:%S")
    except ValueError:
        return captured_at
    return parsed.strftime("%d/%m/%Y %H:%M")
